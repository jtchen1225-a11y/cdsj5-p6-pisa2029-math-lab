// Show Toast
function showToast(msg) {
  toastEl.textContent = msg;
  toastEl.classList.add('show');
  setTimeout(() => toastEl.classList.remove('show'), 2200);
}

// Populate Sidebar
function populateSidebar() {
  lessonList.innerHTML = '';
  const searchVal = lessonSearch.value.trim().toLowerCase();

  LESSONS_DATA.forEach(l => {
    // Filter by term
    if (currentFilter === 't1' && l.week > 15) return;
    if (currentFilter === 't2' && l.week <= 15) return;

    // Filter by search
    if (searchVal) {
      const match = l.title.toLowerCase().includes(searchVal) ||
                    l.unit.toLowerCase().includes(searchVal) ||
                    l.domain.toLowerCase().includes(searchVal) ||
                    String(l.week).includes(searchVal);
      if (!match) return;
    }

    const item = document.createElement('div');
    item.className = `lesson-item ${l.week === currentWeek ? 'active' : ''}`;
    item.onclick = () => loadWeek(l.week);
    item.innerHTML = `
      <div class="item-top">
        <span class="item-week">第 ${String(l.week).padStart(2, '0')} 週</span>
        <span class="item-domain">${l.domain.split(' ')[0]}</span>
      </div>
      <div class="item-title">${l.title}</div>
    `;
    lessonList.appendChild(item);
  });
}

// Populate Dropdown
function populateDropdown() {
  weekSelect.innerHTML = '';
  LESSONS_DATA.forEach(l => {
    const opt = document.createElement('option');
    opt.value = l.week;
    opt.textContent = `第 ${String(l.week).padStart(2, '0')} 週: ${l.title.substring(0, 22)}...`;
    weekSelect.appendChild(opt);
  });
  weekSelect.value = currentWeek;
}

// Setup Event Listeners
function setupEventListeners() {
  sidebarToggle.onclick = () => sidebar.classList.toggle('collapsed');
  btnPrevWeek.onclick = () => { if (currentWeek > 1) loadWeek(currentWeek - 1); };
  btnNextWeek.onclick = () => { if (currentWeek < 30) loadWeek(currentWeek + 1); };
  weekSelect.onchange = (e) => loadWeek(parseInt(e.target.value));

  btnToggleCER.onclick = () => cerCard.classList.toggle('collapsed');
  cerHeader.onclick = () => cerCard.classList.toggle('collapsed');

  filterTabs.forEach(tab => {
    tab.onclick = () => {
      filterTabs.forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      currentFilter = tab.dataset.filter;
      populateSidebar();
    };
  });

  lessonSearch.oninput = () => populateSidebar();

  btnFullscreen.onclick = () => {
    if (!document.fullscreenElement) {
      document.documentElement.requestFullscreen().catch(() => {});
    } else {
      document.exitFullscreen().catch(() => {});
    }
  };

  // Keyboard navigation
  window.addEventListener('keydown', (e) => {
    if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA') return;
    if (e.key === 'ArrowLeft') {
      if (currentWeek > 1) loadWeek(currentWeek - 1);
    } else if (e.key === 'ArrowRight') {
      if (currentWeek < 30) loadWeek(currentWeek + 1);
    } else if (e.key.toLowerCase() === 'r') {
      const resetBtn = document.getElementById('btnResetExp');
      if (resetBtn) resetBtn.click();
    } else if (e.key.toLowerCase() === 'c') {
      cerCard.classList.toggle('collapsed');
    }
  });

  document.getElementById('btnClearTable').onclick = () => {
    recordedTables[currentWeek] = [];
    renderObservationTable(LESSONS_DATA[currentWeek - 1]);
    showToast('觀測表已清空');
  };

  document.getElementById('btnRecordData').onclick = () => {
    recordCurrentData();
  };
}

// Load Week
function loadWeek(week) {
  if (animationFrameId) {
    cancelAnimationFrame(animationFrameId);
    animationFrameId = null;
  }

  currentWeek = week;
  weekSelect.value = week;
  btnPrevWeek.disabled = (week === 1);
  btnNextWeek.disabled = (week === 30);

  const lesson = LESSONS_DATA[week - 1];

  // Banner
  document.getElementById('bannerWeek').textContent = `第 ${String(lesson.week).padStart(2, '0')} 週`;
  document.getElementById('bannerDomain').textContent = lesson.domain;
  document.getElementById('bannerUnit').textContent = lesson.unit;
  document.getElementById('bannerTitle').textContent = lesson.title;
  document.getElementById('bannerCoords').textContent = lesson.pisa_coords;

  // Context & Guide
  document.getElementById('contextText').textContent = lesson.text_scrutiny;
  document.getElementById('misconceptionText').textContent = lesson.misconception;
  document.getElementById('expPrinciple').textContent = `★ 實驗原理：${lesson.exp_principle}`;

  const stepsList = document.getElementById('expStepsList');
  stepsList.innerHTML = '';
  lesson.exp_steps.forEach(st => {
    const li = document.createElement('li');
    li.textContent = st;
    stepsList.appendChild(li);
  });

  // CER
  document.getElementById('cerClaim').textContent = lesson.cer.claim;
  document.getElementById('cerEvidence').textContent = lesson.cer.evidence;
  document.getElementById('cerReasoning').textContent = lesson.cer.reasoning;
  document.getElementById('cerRebuttal').textContent = lesson.cer.rebuttal;
  cerCard.classList.add('collapsed');

  // CPS Challenge
  document.getElementById('cpsChallengeText').textContent = lesson.cps_challenge;

  // Sandbox Name
  document.getElementById('sandboxName').textContent = lesson.exp_name;

  // Update Observation Table
  if (!recordedTables[week]) {
    recordedTables[week] = JSON.parse(JSON.stringify(lesson.table_rows));
  }
  renderObservationTable(lesson);

  // Update active sidebar item
  populateSidebar();

  // Mount specific experiment
  mountExperiment(week);
}

// Render Observation Table
function renderObservationTable(lesson) {
  const thead = document.getElementById('obsThead');
  const tbody = document.getElementById('obsTbody');

  thead.innerHTML = '<tr>' + lesson.table_headers.map(h => `<th>${h}</th>`).join('') + '</tr>';

  const rows = recordedTables[lesson.week] || [];
  tbody.innerHTML = rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('');
}

// Record current experiment parameters to table
let currentRecordGetter = null;
function recordCurrentData() {
  if (currentRecordGetter) {
    const newRow = currentRecordGetter();
    if (newRow) {
      recordedTables[currentWeek].push(newRow);
      renderObservationTable(LESSONS_DATA[currentWeek - 1]);
      showToast('已記錄一筆觀測數據！');
    }
  } else {
    showToast('當前實驗台數據已保存');
  }
}

